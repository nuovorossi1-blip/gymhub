import {test,expect} from '@playwright/test';
test('JM press: cercabile prima di importazione, video corretto, guida animata e aggiunta personale persistente',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/?screen=library');await expect(page.locator('#avvio')).toHaveCount(0);
 const search=page.getByRole('searchbox',{name:'Cerca esercizio'});
 await search.fill('jm press');
 await expect(page.locator('.exercise-card')).toHaveCount(1);
 await expect(page.locator('.exercise-card')).toContainText('JM press bilanciere');
 await page.locator('.exercise-card').click();
 let d=page.getByRole('dialog');
 await expect(d).toContainText('COME SI ESEGUE');
 await expect(d).toContainText('bilanciere');
 await expect(d.getByRole('link',{name:/Weight Training Guide/})).toHaveAttribute('href','https://weighttraining.guide/exercises/barbell-jm-press/');
 await expect(d.getByRole('link',{name:/EliteFTS/})).toHaveAttribute('href',/elitefts\.com/);
 await expect(d.getByRole('link',{name:/Dimostrazione originale/})).toHaveAttribute('href',/ynbS3UZT2O8&t=462s/);
 await d.getByRole('button',{name:'Aggiungi ai miei esercizi'}).click();
 await expect(page.locator('.exercise-card')).toHaveCount(1);
 await page.locator('.exercise-card').click();
 d=page.getByRole('dialog');
 await expect(d).toContainText('COME SI ESEGUE');
 await expect(d.getByRole('button',{name:'Modifica dettagli'})).toBeVisible();
 await d.getByRole('button',{name:'Chiudi'}).click();
 await page.reload();await expect(page.locator('#avvio')).toHaveCount(0);
 await page.getByRole('searchbox',{name:'Cerca esercizio'}).fill('barbell jm press');
 await expect(page.locator('.exercise-card')).toHaveCount(1);
 await page.locator('.exercise-card').click();
 await expect(page.getByRole('dialog')).toContainText('Weight Training Guide');
 expect(errors).toEqual([]);
});
test('catalogo e filtri: no media copiati, 320px senza overflow, utente invariato',async({page})=>{
 await page.setViewportSize({width:320,height:800});
 await page.goto('/?screen=library');await expect(page.locator('#avvio')).toHaveCount(0);
 await page.getByRole('searchbox',{name:'Cerca esercizio'}).fill('JM Blakley press');
 await expect(page.locator('.exercise-card')).toHaveCount(1);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
 await page.locator('.exercise-card').click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
 await page.getByRole('dialog').getByRole('button',{name:'Chiudi'}).click();
 await page.getByRole('searchbox',{name:'Cerca esercizio'}).fill('JM press');
 await page.locator('[data-action="filter-muscle"][data-muscle="Gambe"]').click();
 await expect(page.locator('.exercise-card')).toHaveCount(0);
 await page.locator('[data-action="filter-muscle"][data-muscle="Tricipiti"]').click();
 await expect(page.locator('.exercise-card')).toHaveCount(1);
});
