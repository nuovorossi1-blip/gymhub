import {test,expect} from '@playwright/test';
test('Chris 2019: leggi split, attiva in Oggi, modifica le tue schede, runner, recupero e storico',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.clock.install({time:new Date('2027-01-04T12:00:00+01:00')});
 await page.goto('/');await expect(page.locator('#avvio')).toHaveCount(0);
 await page.locator('.mobile-nav').getByRole('button',{name:'Schede',exact:true}).click();
 await page.locator('[data-action="library-ppl"]').click();
 await expect(page.locator('.program-session')).toHaveCount(6);
 await expect(page.locator('.program-intro')).toContainText('IAIN VALLIERE');
 await page.locator('[data-action="library-ppl-session"][data-id="pull-b"]').click();
 await expect(page.getByRole('dialog')).toContainText('2 × 20');
 await page.getByRole('dialog').getByRole('button',{name:'Chiudi'}).click();
 await page.locator('.mobile-nav').getByRole('button',{name:'Oggi',exact:true}).click();
 await page.getByRole('button',{name:'Scegli split e ciclo'}).click();
 await page.getByRole('dialog').locator('[data-action="activate-ppl"]').click();
 let d=page.getByRole('dialog');
 await d.getByLabel('Data di partenza').fill('2027-01-04');await d.getByLabel('Quanti cicli').selectOption('1');
 await expect(d.locator('.cycle-day')).toHaveCount(8);
 await expect(d.locator('.rest-day')).toHaveCount(2);
 await d.getByRole('button',{name:'Aggiungi schede e calendario'}).click();
 await page.getByRole('button',{name:'Gestisci le mie schede'}).click();
 await expect(page.locator('.plan-card')).toHaveCount(7);
 const pull=page.locator('.plan-card').filter({has:page.getByRole('heading',{name:'Pull A · Chris 2019',exact:true})});
 await pull.getByRole('button',{name:'Modifica'}).click();d=page.getByRole('dialog');
 await expect(d.getByLabel('Tipo di serie esercizio 8')).toHaveValue('time');
 await d.getByRole('button',{name:'Salva',exact:true}).click();
 await pull.getByRole('button',{name:'Inizia',exact:true}).click();
 let timed=page.locator('.runner-card').filter({has:page.getByRole('button',{name:'Avvia serie 40s'})});
 await expect(timed.locator('[data-property="reps"]').first()).toHaveValue('');
 await timed.getByRole('button',{name:'Avvia serie 40s'}).click();
 await expect(page.locator('#effort-panel')).toContainText('SERIE IN CORSO');
 await timed.locator('[data-property="kg"]').first().fill('10');
 await timed.locator('[data-property="reps"]').first().fill('15');
 await page.reload();await expect(page.locator('#avvio')).toHaveCount(0);
 await page.getByRole('button',{name:'Riprendi allenamento'}).click();
 await expect(page.locator('#effort-panel')).toHaveCount(0);
 await expect(timed.locator('[data-property="reps"]').first()).toHaveValue('15');
 await page.getByRole('button',{name:'Riprendi',exact:true}).click();
 await timed.locator('.set-check').first().click();
 await page.getByRole('button',{name:'Concludi allenamento'}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Salva allenamento'}).click();
 await expect(page.locator('.history-card')).toContainText('150');
 await page.locator('.mobile-nav').getByRole('button',{name:'Oggi',exact:true}).click();
 await page.getByRole('button',{name:'Scegli split e ciclo'}).click();
 await page.getByRole('dialog').locator('[data-action="activate-ppl"]').click();
 d=page.getByRole('dialog');await d.getByLabel('Data di partenza').fill('2027-01-04');
 await d.getByRole('button',{name:'Aggiungi schede e calendario'}).click();
 await expect(d.locator('.form-error')).toContainText('già pianificato');
 expect(errors).toEqual([]);
});
