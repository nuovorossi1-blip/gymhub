import { test, expect } from '@playwright/test';

test('tutorial esterno da libreria e allenamento, link personale e accesso scheda Chris', async ({ page, context }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await context.route('https://www.youtube.com/**', route => route.fulfill({ contentType: 'text/html', body: '<title>Video esterno di prova</title>' }));
  await page.goto('/'); await expect(page.locator('#avvio')).toHaveCount(0);
  await page.locator('.mobile-nav').getByRole('button', { name: 'Esercizi', exact: true }).click();
  await page.getByRole('button', { name: /Panca piana/ }).click();
  let d = page.getByRole('dialog');
  await expect(d.getByRole('link', { name: /Guarda su YouTube/ })).toHaveAttribute('href', 'https://www.youtube.com/watch?v=rT7DgCr-3pg');
  await page.screenshot({ path: 'artifacts/screenshots/20-exercise-youtube.png', fullPage: true });
  const popupPromise = context.waitForEvent('page');
  await d.getByRole('link', { name: /Guarda su YouTube/ }).click();
  const external = await popupPromise; await external.waitForLoadState();
  expect(external.url()).toBe('https://www.youtube.com/watch?v=rT7DgCr-3pg'); await external.close();
  await d.getByRole('button', { name: 'Chiudi', exact: true }).click();
  await page.getByRole('button', { name: 'Nuovo esercizio', exact: true }).click(); d = page.getByRole('dialog');
  await d.getByLabel('Nome', { exact: true }).fill('La mia variante');
  await d.getByLabel('Video YouTube (facoltativo)').fill('https://youtu.be/8iPEnn-ltC8?t=30');
  await d.getByRole('button', { name: 'Salva', exact: true }).click();
  await page.reload(); await expect(page.locator('#avvio')).toHaveCount(0);
  await page.locator('.mobile-nav').getByRole('button', { name: 'Esercizi', exact: true }).click();
  await page.getByRole('button', { name: /La mia variante/ }).click(); d = page.getByRole('dialog');
  await expect(d.getByRole('link', { name: /Guarda su YouTube/ })).toHaveAttribute('href', 'https://www.youtube.com/watch?v=8iPEnn-ltC8&t=30');
  await d.getByRole('button', { name: 'Modifica dettagli' }).click(); d = page.getByRole('dialog');
  await d.getByLabel('Video YouTube (facoltativo)').fill('https://example.com/video');
  await d.getByRole('button', { name: 'Salva', exact: true }).click();
  await expect(d.locator('.form-error')).toContainText('singolo video YouTube');
  await d.getByLabel('Video YouTube (facoltativo)').fill(''); await d.getByRole('button', { name: 'Salva', exact: true }).click();
  await page.getByRole('button', { name: /La mia variante/ }).click(); d = page.getByRole('dialog');
  await expect(d.getByRole('link', { name: /Cerca su YouTube/ })).toHaveAttribute('href', /results\?search_query=/);
  await d.getByRole('button', { name: 'Chiudi', exact: true }).click();
  await page.locator('.mobile-nav').getByRole('button', { name: 'Schede', exact: true }).click();
  await page.getByRole('button', { name: 'Nuova scheda', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Petto, gambe e altri giorni non sono ancora inclusi');
  await page.screenshot({ path: 'artifacts/screenshots/21-new-plan-choice.png', fullPage: true });
  await page.getByRole('button', { name: /Chris Bumstead · Schiena/ }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Aggiungi scheda' }).click();
  const plan = page.locator('.plan-card').filter({ has: page.getByRole('heading', { name: 'Schiena · Chris Bumstead', exact: true }) });
  await plan.getByRole('button', { name: 'Inizia', exact: true }).click();
  const card = page.locator('.runner-card').first();
  await card.locator('[data-property="kg"]').first().fill('45');
  await card.getByRole('button', { name: 'Come si esegue · YouTube' }).click(); d = page.getByRole('dialog');
  await expect(d.getByRole('link', { name: /Guarda su YouTube/ })).toHaveAttribute('href', 'https://www.youtube.com/watch?v=ZQPVYJc1cpM&t=25s');
  await d.getByRole('button', { name: 'Chiudi', exact: true }).click();
  await expect(card.locator('[data-property="kg"]').first()).toHaveValue('45');
  expect(errors).toEqual([]);
});
